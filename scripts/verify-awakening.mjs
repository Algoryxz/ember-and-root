import { chromium, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { mkdir, writeFile } from 'node:fs/promises';

const output = 'docs/screenshots/awakening';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome' });
const report = [];
try {
  for (const [width, height] of [[1440, 900], [768, 1024], [390, 844], [375, 812], [320, 700]]) {
    const context = await browser.newContext({ viewport: { width, height }, hasTouch: width < 500 });
    const page = await context.newPage();
    const errors = [];
    const writes = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => { if (request.method() !== 'GET') writes.push(request.url()); });
    await page.goto('http://localhost:4123/awakening');
    await page.evaluate(() => document.fonts.ready);
    const scene = page.locator('main');
    const action = page.locator('.awakening-primary');
    await expect(action).toHaveAttribute('aria-disabled', 'false');
    await expect(scene).toHaveAttribute('data-beat', 'dark');
    await page.screenshot({ path: `${output}/${width}-dark.png` });
    await action.focus();
    await page.keyboard.press('Enter');
    await expect(scene).toHaveAttribute('data-beat', 'lit');
    await page.waitForTimeout(1500);
    await page.screenshot({ path: `${output}/${width}-human.png` });
    if (width === 1440) {
      await page.mouse.move(100, 300);
      const before = await page.locator('#aw-local').getAttribute('cx');
      await page.mouse.move(1300, 500);
      expect(await page.locator('#aw-local').getAttribute('cx')).not.toBe(before);
    }
    await action.press('Enter');
    await expect(scene).toHaveAttribute('data-beat', 'ember');
    await page.waitForTimeout(1300);
    await page.screenshot({ path: `${output}/${width}-ember.png` });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    const bounds = await action.boundingBox();
    expect(bounds.height).toBeGreaterThanOrEqual(44);
    expect(bounds.y + bounds.height).toBeLessThanOrEqual(height);
    const a11y = await new AxeBuilder({ page }).analyze();
    expect(a11y.violations).toEqual([]);
    await action.press('Enter');
    await expect(scene).toHaveAttribute('data-beat', 'dark');
    await action.press('Enter');
    await page.getByRole('button', { name: 'Skip to Ember' }).click();
    await page.waitForTimeout(2100);
    await expect(scene).toHaveAttribute('data-beat', 'ember');
    expect(errors).toEqual([]);
    expect(writes).toEqual([]);
    report.push({ width, height, keyboard: 'pass', replayAndSkipCancellation: 'pass', axe: 'pass', overflow: 'none', browserErrors: errors, mutationRequests: writes });
    await context.close();
  }
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce', hasTouch: true });
  await page.goto('http://localhost:4123/awakening');
  await expect(page.locator('main')).toHaveAttribute('data-reduced', 'true');
  await page.getByRole('button', { name: 'Strike the match' }).tap();
  await expect(page.locator('main')).toHaveAttribute('data-beat', 'lit');
  await page.getByRole('button', { name: 'Bring the light within' }).tap();
  await expect(page.locator('main')).toHaveAttribute('data-beat', 'ember');
  expect(await page.locator('.aw-core').evaluate(el => getComputedStyle(el).animationName)).toBe('none');
  await page.screenshot({ path: `${output}/390-reduced.png` });
  report.push({ reducedMotionTouch: 'pass' });
  await page.close();
  const zoom = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  await zoom.goto('http://localhost:4123/awakening');
  await zoom.evaluate(() => { document.documentElement.style.zoom = '2'; });
  await zoom.getByRole('button', { name: 'Strike the match' }).click();
  await zoom.getByRole('button', { name: 'Bring the light within' }).click();
  await expect(zoom.locator('main')).toHaveAttribute('data-beat', 'ember');
  expect(await zoom.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await zoom.screenshot({ path: `${output}/200-percent-zoom.png`, fullPage: true });
  report.push({ cssZoom200Percent: 'pass' });
  await zoom.close();
  const failure = await browser.newPage();
  await failure.route('**/hero/awakening-human.png*', route => route.abort());
  await failure.goto('http://localhost:4123/awakening');
  await expect(failure.locator('main').getByRole('alert')).toContainText('The scene could not load');
  await failure.unroute('**/hero/awakening-human.png*');
  await failure.getByRole('button', { name: 'Reload scene' }).click();
  await expect(failure.locator('.awakening-primary')).toHaveAttribute('aria-disabled', 'false');
  await failure.getByRole('button', { name: 'Strike the match' }).click();
  await expect(failure.locator('main')).toHaveAttribute('data-beat', 'lit');
  report.push({ assetFailureRecovery: 'pass' });
  await failure.close();
  await writeFile(`${output}/verification.json`, JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
} finally { await browser.close(); }
